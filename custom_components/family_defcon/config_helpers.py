# work factor keeps a full invalid-PIN scan responsive while still avoiding the
# effectively uncosted SHA256 hashes used by earlier releases.
PIN_HASH_ITERATIONS = 20_000
# Accept hashes generated by the earlier 120,000-iteration beta, but reject
# larger imported work factors that could stall an eight-person PIN scan.
MAX_PIN_HASH_ITERATIONS = 120_000

